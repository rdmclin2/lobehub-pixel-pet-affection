#!/usr/bin/env node
// Export the design tokens the project uses (admin/src/design/tokens.ts) from @lobehub/ui's theme.css into
// plain files the vanilla-JS windows can read without the React bundle:
//
//   src/renderer/design/lobe-tokens.css   light + dark `--lobe-*` values (+ `--pet-space-*`), follows data-theme
//                                          and, without data-theme, prefers-color-scheme
//   src/renderer/design/tokens.json       the same values as data (role, cssVar key, light, dark)
//
// Both are committed (they live under build.files `src/**`, so they ship in the package) and regenerated with
// `npm run design:tokens`. `--check` exits 1 when the committed files differ from what would be generated
// (test/design-system.test.js runs it), so an @lobehub/ui upgrade or a tokens.ts edit cannot drift silently.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const OUT_DIR = path.join(ROOT, 'src', 'renderer', 'design');
const check = process.argv.includes('--check');

const themeFile = require.resolve('@lobehub/ui/theme.css');
const themeCss = fs.readFileSync(themeFile, 'utf8');
const uiPkg = JSON.parse(fs.readFileSync(path.join(path.dirname(themeFile), '..', 'package.json'), 'utf8')); // package.json is not in `exports`
const skillVersion = (fs.readFileSync(path.join(ROOT, '.agents/skills/lobe-design/SKILL.md'), 'utf8').match(/^version:\s*(\S+)/m) || [])[1];

// --- tokens.ts: role entries `t('key', 'role')`, extra lineHeight keys and the `space` scale -------------
const tokensTs = fs.readFileSync(path.join(ROOT, 'admin/src/design/tokens.ts'), 'utf8');
const entries = [];
const seen = new Set();
const add = (key, role, group) => { if (!seen.has(key)) { seen.add(key); entries.push({ key, role, group }); } };
const groupOf = (key) =>
  key.startsWith('color') ? 'color'
    : /^(fontSize|lineHeight|fontFamily|fontWeight)/.test(key) ? 'typography'
      : key.startsWith('borderRadius') ? 'radius'
        : key.startsWith('boxShadow') ? 'shadow'
          : key.startsWith('motion') ? 'motion'
            : key.startsWith('padding') ? 'spacing'
              : key.startsWith('controlHeight') ? 'control' : 'other';
for (const m of tokensTs.matchAll(/t\('(\w+)',\s*'([^']*)'\)/g)) add(m[1], m[2], groupOf(m[1]));
for (const m of tokensTs.matchAll(/lineHeight:\s*'(\w+)'/g)) add(m[1], '行高', 'typography');
add('fontWeightStrong', '标题字重', 'typography');
const spaceBlock = tokensTs.match(/export const space = \{([\s\S]*?)\}/);
const space = Object.fromEntries([...spaceBlock[1].matchAll(/(\w+):\s*(\d+)/g)].map((m) => [m[1], Number(m[2])]));

// --- theme.css: the light block (`:root, [data-theme='light']`) and the dark block (`[data-theme='dark']`) --
const block = (selector) => {
  const start = themeCss.indexOf(selector + ' {');
  if (start < 0) throw new Error(`theme.css: ${selector} not found`);
  const body = themeCss.slice(start + selector.length + 2, themeCss.indexOf('\n}', start));
  return Object.fromEntries([...body.matchAll(/(--lobe-[\w-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
};
const light = block(":root, [data-theme='light']");
const dark = block("[data-theme='dark']");

const kebab = (key) => '--lobe-' + key.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([a-zA-Z])(\d)/g, '$1-$2').toLowerCase();
const rows = entries.map(({ key, role, group }) => {
  const name = kebab(key);
  const l = light[name];
  if (l === undefined) throw new Error(`${key} → ${name} is not defined in @lobehub/ui/theme.css`);
  return { key, var: name, role, group, light: l, dark: dark[name] ?? l };
});

const header = `Generated by scripts/build-design-tokens.mjs from @lobehub/ui@${uiPkg.version} es/theme.css (lobe-design ${skillVersion}). Do not edit; run \`npm run design:tokens\`.`;
const decl = (pick) => rows.map((r) => `  ${r.var}: ${pick(r)};`).join('\n');
const darkOnly = rows.filter((r) => r.dark !== r.light);
const css = `/* ${header}
 * Light/dark follow <html data-theme="light|dark">; without the attribute they follow prefers-color-scheme.
 * Project-only spacing uses the --pet- prefix (lobe-design D-07: never redefine --lobe-* values). */
:root,
[data-theme='light'] {
${decl((r) => r.light)}
${Object.entries(space).map(([k, v]) => `  --pet-space-${k}: ${v}px;`).join('\n')}
}

[data-theme='dark'] {
${darkOnly.map((r) => `  ${r.var}: ${r.dark};`).join('\n')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme]) {
${darkOnly.map((r) => `    ${r.var}: ${r.dark};`).join('\n')}
  }
}
`;
const json = JSON.stringify({ $comment: header, source: { package: '@lobehub/ui', version: uiPkg.version, file: 'es/theme.css' }, skill: { name: 'lobe-design', version: skillVersion }, space, tokens: rows }, null, 2) + '\n';

const files = { 'lobe-tokens.css': css, 'tokens.json': json };
let stale = 0;
for (const [name, content] of Object.entries(files)) {
  const file = path.join(OUT_DIR, name);
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (check) {
    if (current !== content) { stale++; console.log(`STALE ${path.relative(ROOT, file)}`); } else console.log(`ok    ${path.relative(ROOT, file)}`);
  } else {
    fs.mkdirSync(OUT_DIR, { recursive: true });
    fs.writeFileSync(file, content);
    console.log(`wrote ${path.relative(ROOT, file)} (${rows.length} tokens, ${darkOnly.length} with a dark value, ${Object.keys(space).length} space steps)`);
  }
}
process.exit(stale ? 1 : 0);
